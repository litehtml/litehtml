litehtml::el_before_after_base::el_before_after_base(const std::shared_ptr<document>& doc, bool before) :
    html_tag(doc)
{
    m_tag = before ? __tag_before_ : __tag_after_;
}

void litehtml::el_before_after_base::add_style(const style& style)
{
    html_tag::add_style(style);

    auto children = m_children;
    m_children.clear();

    const auto& content_property = style.get_property(_content_);
    if(content_property.is<std::string>())
    {
        // Quote text depends on the document-wide nesting level, which is only known after all styles have
        // been applied. resolve_quotes() replaces the quote text in document order; the rest of the content
        // (including counter() and attr()) must be generated here to preserve the counter order.
        m_quotes_resolved = false;
        m_quote_spans.clear();
        if(!content_property.get<std::string>().empty())
        {
            int quote_depth = 0;
            parse_content(content_property.get<std::string>(), quote_depth, get_quotes());
        }
    } else
    {
        // The matched rule does not declare `content`; keep the content generated by other rules.
        m_children = children;
    }
}

void litehtml::el_before_after_base::compute_styles(bool recursive)
{
    html_tag::compute_styles(recursive);

    // A ::before/::after pseudo-element generates a box only when its `content` is not `normal`. The element
    // is kept in the tree so declarations from all matching pseudo rules combine, but it must not take part
    // in layout when nothing is generated (for example a rule that only sets padding).
    bool generates = false;
    if(const property_value* content = m_style.find_property(_content_))
    {
        if(content->is<std::string>())
        {
            const auto& value = content->get<std::string>();
            generates         = value != "none" && value != "normal";
        }
    }
    if(!generates)
    {
        css().set_display(display_none);
    }
}

bool litehtml::el_before_after_base::resolve_quotes(int& quote_depth)
{
    if(m_quote_spans.empty())
    {
        return false;
    }

    const css_quotes quotes = get_quotes();

    if(m_quotes_resolved && quote_depth == m_resolved_depth && quotes == m_resolved_quotes)
    {
        for(const auto& span : m_quote_spans)
        {
            advance_quote_depth(span.action, quote_depth);
        }
        return false;
    }

    const int start_depth = quote_depth;

    std::vector<elements_list> replacements;
    replacements.reserve(m_quote_spans.size());
    for(const auto& span : m_quote_spans)
    {
        elements_list text;
        switch(span.action)
        {
        case quote_action::open:
            append_text(text, quotes.open_quote(quote_depth));
            ++quote_depth;
            break;
        case quote_action::close:
            if(quote_depth > 0)
            {
                --quote_depth;
                append_text(text, quotes.close_quote(quote_depth));
            }
            break;
        case quote_action::no_open:
            ++quote_depth;
            break;
        case quote_action::no_close:
            if(quote_depth > 0)
            {
                --quote_depth;
            }
            break;
        }
        replacements.push_back(std::move(text));
    }

    // Replace the text from the last keyword to the first one, so the recorded child indexes stay valid.
    bool replaced = false;
    for(std::size_t i = m_quote_spans.size(); i-- > 0;)
    {
        auto it = m_children.begin();
        for(std::size_t n = 0; n < m_quote_spans[i].index && it != m_children.end(); ++n)
        {
            ++it;
        }

        std::string old_text;
        auto        old_it = it;
        for(std::size_t n = 0; n < m_quote_spans[i].count && old_it != m_children.end(); ++n, ++old_it)
        {
            (*old_it)->get_text(old_text);
        }
        std::string new_text;
        for(const auto& child : replacements[i])
        {
            child->get_text(new_text);
        }
        if(old_text == new_text)
        {
            continue;
        }

        for(std::size_t n = 0; n < m_quote_spans[i].count && it != m_children.end(); ++n)
        {
            it = m_children.erase(it);
        }
        m_children.splice(it, replacements[i]);
        replaced = true;
    }

    m_quotes_resolved = true;
    m_resolved_depth  = start_depth;
    m_resolved_quotes = quotes;
    return replaced;
}

void litehtml::el_before_after_base::parse_content(const std::string& content, int& quote_depth,
                                                   const css_quotes& quotes)
{
    const auto add_keyword = [&](std::string keyword) {
        litehtml::lcase(keyword);
        const auto idx = css_values(content_property_strings).value_index(keyword);
        if(!idx.has_value())
        {
            return;
        }
        const auto   begin = m_children.size();
        quote_action action;
        switch(static_cast<content_property>(idx.value()))
        {
        case content_property_open_quote:
            action = quote_action::open;
            add_text(quotes.open_quote(quote_depth));
            break;
        case content_property_close_quote:
            action = quote_action::close;
            if(quote_depth > 0)
            {
                add_text(quotes.close_quote(quote_depth - 1));
            }
            break;
        case content_property_no_open_quote:
            action = quote_action::no_open;
            break;
        case content_property_no_close_quote:
            action = quote_action::no_close;
            break;
        default:
            return; // none, normal
        }
        m_quote_spans.push_back({begin, m_children.size() - begin, action});
        advance_quote_depth(action, quote_depth);
    };

    std::string            fnc;
    std::string::size_type i = 0;
    while(i < content.length() && i != std::string::npos)
    {
        const char chr = content.at(i);
        if(chr == '"' || chr == '\'')
        {
            fnc.clear();
            i++;
            std::string::size_type pos = content.find(chr, i);
            std::string            txt;
            if(pos == std::string::npos)
            {
                txt = content.substr(i);
                i   = std::string::npos;
            } else
            {
                txt = content.substr(i, pos - i);
                i   = pos + 1;
            }
            add_text(txt);
        } else if(chr == '(')
        {
            i++;
            litehtml::trim(fnc);
            litehtml::lcase(fnc);
            std::string::size_type pos = content.find(')', i);
            std::string            params;
            if(pos == std::string::npos)
            {
                params = content.substr(i);
                i      = std::string::npos;
            } else
            {
                params = content.substr(i, pos - i);
                i      = pos + 1;
            }
            add_function(fnc, params);
            fnc.clear();
        } else if(std::isspace(static_cast<unsigned char>(chr)))
        {
            if(!fnc.empty())
            {
                add_keyword(fnc);
                fnc.clear();
            }
            i++;
        } else
        {
            fnc += chr;
            i++;
        }
    }
    if(!fnc.empty())
    {
        add_keyword(fnc);
    }
}

void litehtml::el_before_after_base::advance_quote_depth(quote_action action, int& depth)
{
    switch(action)
    {
    case quote_action::open:
    case quote_action::no_open:
        ++depth;
        break;
    case quote_action::close:
    case quote_action::no_close:
        if(depth > 0)
        {
            --depth;
        }
        break;
    }
}

void litehtml::el_before_after_base::add_text(const std::string& txt)
{
    append_text(m_children, txt);
}

void litehtml::el_before_after_base::append_text(elements_list& children, const std::string& txt)
{
    std::string word;
    std::string esc;

    const auto append = [&](const element::ptr& el) {
        el->parent(shared_from_this());
        children.push_back(el);
    };

    for(auto chr : txt)
    {
        if(chr == '\\' || (!esc.empty() && esc.length() < 5 &&
                           ((chr >= '0' && chr <= '9') || (chr >= 'A' && chr <= 'Z') || (chr >= 'a' && chr <= 'z'))))
        {
            if(!esc.empty() && chr == '\\')
            {
                word += convert_escape(esc.c_str() + 1);
                esc.clear();
            }
            esc += chr;
        } else
        {
            if(!esc.empty())
            {
                word += convert_escape(esc.c_str() + 1);
                esc.clear();
            }
            if(isspace(static_cast<unsigned char>(chr)))
            {
                if(!word.empty())
                {
                    append(std::make_shared<el_text>(word.c_str(), get_document()));
                    word.clear();
                }
                word += chr;
                append(std::make_shared<el_space>(word.c_str(), get_document()));
                word.clear();
            } else
            {
                word += chr;
            }
        }
    }

    if(!esc.empty())
    {
        word += convert_escape(esc.c_str() + 1);
    }
    if(!word.empty())
    {
        append(std::make_shared<el_text>(word.c_str(), get_document()));
        word.clear();
    }
}

void litehtml::el_before_after_base::add_function(const std::string& fnc, const std::string& params)
{
    constexpr auto content_function_strings = split_css_values<4>("attr;counter;counters;url");

    auto idx = css_values(content_function_strings).value_index(fnc);
    if(!idx.has_value())
    {
        return;
    }
    switch(idx.value())
    {
    // attr
    case 0:
        {
            std::string p_name = params;
            trim(p_name);
            lcase(p_name);
            element::ptr el_parent = parent();
            if(el_parent)
            {
                const char* attr_value = el_parent->get_attr(p_name.c_str());
                if(attr_value)
                {
                    add_text(attr_value);
                }
            }
        }
        break;
    // counter
    case 1:
        add_text(get_counter_value(params));
        break;
    // counters
    case 2:
        {
            string_vector tokens;
            split_string(params, tokens, ",");
            for(auto& str : tokens)
            {
                trim(str);
            }
            add_text(get_counters_value(tokens));
        }
        break;
    // url
    case 3:
        {
            std::string p_url = params;
            trim(p_url);
            if(!p_url.empty())
            {
                if(p_url.at(0) == '\'' || p_url.at(0) == '\"')
                {
                    p_url.erase(0, 1);
                }
            }
            if(!p_url.empty())
            {
                if(p_url.at(p_url.length() - 1) == '\'' || p_url.at(p_url.length() - 1) == '\"')
                {
                    p_url.erase(p_url.length() - 1, 1);
                }
            }
            if(!p_url.empty())
            {
                element::ptr el = std::make_shared<el_image>(get_document());
                el->set_attr("src", p_url.c_str());
                el->set_attr("style", "display:inline-block");
                el->set_tagName("img");
                appendChild(el);
                el->parse_attributes();
            }
        }
        break;
    }
}

std::string litehtml::el_before_after_base::convert_escape(const char* txt)
{
    char*    str_end;
    char32_t u_str[2];
    u_str[0] = static_cast<char32_t>(strtol(txt, &str_end, 16));
    u_str[1] = 0;
    return litehtml_from_utf32(u_str).c_str();
}
